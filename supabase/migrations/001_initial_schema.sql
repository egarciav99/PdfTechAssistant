  for all using (auth.uid() = id) with check (auth.uid() = id);

create policy "Users manage their documents" on public.user_documents
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users read their chunks" on public.document_chunks
  for select using (auth.uid() = user_id);
create policy "Users read their summaries" on public.summaries
  for select using (auth.uid() = user_id);
create policy "Users manage their sessions" on public.chat_sessions
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage their messages" on public.chat_messages
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users read processing errors" on public.processing_errors
  for select using (auth.uid() = user_id);

